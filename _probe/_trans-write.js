/* ---------------- 校验 ---------------- */
// ⚠️ 只查**汉字 + 假名**，别把谚文（\uac00-\ud7af）算进来 ——
//    韩语译文本身就是谚文，一起算的话 61 条全被误判成「残留中文」。
//    这个口径跟 `i18n-check-pack.js` 的 CJK 正则保持一致。
const CJK_RE = /[\u4e00-\u9fff\u3040-\u30ff]/;
let bad = 0;
const seen = new Set();
for (const [key, vals] of TABLE) {
  if (seen.has(key)) { console.error('重复词条: ' + JSON.stringify(key)); bad++; }
  seen.add(key);
  if (vals.length !== CODES.length) {
    console.error(`「${key}」有 ${vals.length} 个译文，应为 ${CODES.length}`);
    bad++; continue;
  }
  // 形状键的 %s 个数两边必须一致，否则回填会错位
  const kn = (key.match(/%s/g) || []).length;
  vals.forEach((v, i) => {
    const code = CODES[i];
    if (!v) { console.error(`「${key}」的 ${code} 译文为空`); bad++; }
    const vn = (v.match(/%s/g) || []).length;
    if (vn !== kn) { console.error(`「${key}」${code}：%s 个数 ${vn} ≠ 原文 ${kn}`); bad++; }
    // 非汉字语言不许残留中日韩文字
    if (!HAN_NATIVE.has(code) && CJK_RE.test(v)) {
      console.error(`「${key}」${code} 译文含 CJK: ${JSON.stringify(v)}`); bad++;
    }
    // 反斜杠不能丢
    const kb = (key.match(/\\/g) || []).length, vb = (v.match(/\\/g) || []).length;
    if (vb < kb) { console.error(`「${key}」${code} 丢了反斜杠`); bad++; }
  });
}
if (bad) { console.error(`\n校验未通过（${bad} 处），未写文件。`); process.exit(1); }
console.log(`校验通过：${TABLE.length} 条 × ${CODES.length} 语言`);

/* ---------------- 写出 ---------------- */
const dir = path.join(__dirname, '_trans');
for (const code of CODES) {
  const file = path.join(dir, code + '.json');
  const old = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : {};
  for (const [key, vals] of TABLE) old[key] = vals[CODES.indexOf(code)];
  fs.writeFileSync(file, JSON.stringify(old, null, 1) + '\n', 'utf8');
}
